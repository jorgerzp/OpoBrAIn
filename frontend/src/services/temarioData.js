// Función para obtener preguntas filtradas según la selección de temas del usuario
export function getPreguntasPorSeleccion({ selectedTopicIds = [], numPreguntas = 10 }) {
  let pool = [];

  if (!selectedTopicIds || selectedTopicIds.length === 0) {
    // Si no ha seleccionado ninguno específico, usar todo el banco
    pool = [...BANCO_PREGUNTAS_REALES];
  } else {
    // Filtrar por los IDs de temas seleccionados (ej: 'b1-t1', 'b3-t3')
    pool = BANCO_PREGUNTAS_REALES.filter((p) => selectedTopicIds.includes(p.temaId));

    // Si por alguna razón la selección no tiene suficientes preguntas exactas en el banco estático,
    // completar con preguntas de los mismos bloques seleccionados
    if (pool.length < numPreguntas) {
      const bloquesElegidos = new Set();
      selectedTopicIds.forEach((id) => {
        const prefijo = id.split('-')[0]; // 'b1', 'b2', etc.
        const bloqueEncontrado = BLOQUES_TEMARIO.find((b) => b.id.includes(prefijo.replace('b', 'bloque-')));
        if (bloqueEncontrado) bloquesElegidos.add(bloqueEncontrado.id);
      });

      const adicionales = BANCO_PREGUNTAS_REALES.filter(
        (p) => bloquesElegidos.has(p.bloqueId) && !pool.some((existente) => existente.id === p.id)
      );
      pool = [...pool, ...adicionales];
    }
  }

  // Si aún queda corto para el número solicitado (ej. 20 o 50), enriquecer mediante muestreo con variación
  if (pool.length === 0) {
    pool = [...BANCO_PREGUNTAS_REALES];
  }

  // Mezclar aleatoriamente el array (Fisher-Yates shuffle)
  const mezcladas = [...pool];
  for (let i = mezcladas.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [mezcladas[i], mezcladas[j]] = [mezcladas[j], mezcladas[i]];
  }

  // Si se piden más preguntas que las disponibles únicas en el pool inicial,
  // clonar con IDs únicos secuenciales para completar el número exacto solicitado por el opositor
  const resultado = [];
  let index = 0;
  while (resultado.length < numPreguntas) {
    const base = mezcladas[index % mezcladas.length];
    resultado.push({
      ...base,
      id: `${base.id}-run-${resultado.length + 1}`,
      numero: resultado.length + 1,
    });
    index++;
  }

  return resultado;
}

